"""Generate the Verilog decoder and the testbench's expected outputs from the Python LUT.

The Python LUT is the single source of truth: the RTL and the test vectors both come from it,
so a hardware bug shows up as a mismatch in simulation.
Bit k of a correction vector is data qubit k; bit k of a syndrome is check k.
"""
from pathlib import Path
from lut_decoder import X_CHECKS, Z_CHECKS, build_lut, check_matrix

RTL = Path(__file__).resolve().parent.parent / "rtl"


def as_int(bits):
    return int(sum(int(b) << k for k, b in enumerate(bits)))


def case_block(lut, signal, out):
    lines = [f"      case ({signal})"]
    for s in range(16):
        lines.append(f"        4'd{s:<2}: {out} <= 9'b{as_int(lut[s]):09b};")
    lines.append("      endcase")
    return "\n".join(lines)


def main():
    lut_x = build_lut(check_matrix(Z_CHECKS))   # X errors, from the Z-check syndrome
    lut_z = build_lut(check_matrix(X_CHECKS))   # Z errors, from the X-check syndrome

    module = f"""// Generated by lut/export_rtl.py. Do not edit by hand.
// Lookup-table decoder for the distance-3 rotated surface code (code-capacity noise).
// One clock cycle from a valid syndrome to a valid correction.
module surface_code_d3_decoder (
    input  wire       clk,
    input  wire       rst,
    input  wire       valid_in,
    input  wire [3:0] syndrome_z,   // Z-check outcomes, flag X errors
    input  wire [3:0] syndrome_x,   // X-check outcomes, flag Z errors
    output reg        valid_out,
    output reg  [8:0] correction_x, // apply X on these data qubits
    output reg  [8:0] correction_z  // apply Z on these data qubits
);
  always @(posedge clk) begin
    if (rst) begin
      valid_out    <= 1'b0;
      correction_x <= 9'b0;
      correction_z <= 9'b0;
    end else begin
      valid_out <= valid_in;
{case_block(lut_x, "syndrome_z", "correction_x")}
{case_block(lut_z, "syndrome_x", "correction_z")}
    end
  end
endmodule
"""
    (RTL / "surface_code_d3_decoder.v").write_text(module)

    # Expected outputs for all 256 syndrome pairs, index = (syndrome_x << 4) | syndrome_z,
    # value = (correction_z << 9) | correction_x, as 18-bit hex.
    with open(RTL / "expected.hex", "w") as f:
        for idx in range(256):
            sz, sx = idx & 0xF, idx >> 4
            f.write(f"{(as_int(lut_z[sx]) << 9) | as_int(lut_x[sz]):05x}\n")
    print("wrote rtl/surface_code_d3_decoder.v and rtl/expected.hex")


if __name__ == "__main__":
    main()
